/**
 * Trích xuất số nhà và tên đường từ chuỗi địa chỉ
 * Hỗ trợ các trường hợp:
 * - "157 Nguyễn Thái Bình" -> houseNumber: "157", streetQuery: "Nguyễn Thái Bình"
 * - "157/24/3 Lê Trọng Tấn, Tây Thạnh" -> houseNumber: "157/24/3", streetQuery: "Lê Trọng Tấn"
 * - "Số 2C Phổ Quang" -> houseNumber: "2C", streetQuery: "Phổ Quang"
 * - "Hẻm 45/2 đường D2" -> houseNumber: "45/2", streetQuery: "D2"
 * - "Đường Nguyễn Thái Bình" -> houseNumber: "", streetQuery: "Nguyễn Thái Bình"
 */
export function extractHouseNumberAndStreet(rawAddress: string): {
  houseNumber: string;
  streetQuery: string;
} {
  const trimmed = (rawAddress || '').trim();
  const firstSegment = trimmed.split(',')[0].trim();

  // Bắt mẫu số nhà đa cấp: "157", "157A", "157/24", "157/24/3A", "2C", "Số 157", "Hẻm 157/2"
  const numMatch = firstSegment.match(
    /^(?:số|ngõ|hẻm|nhà\s*số)?\s*([0-9]+[a-zA-Z]?(?:\/[0-9]+[a-zA-Z]*)*|[0-9]+[a-zA-Z]?)\s+(?:đường|đ\.|phố|đại\s*lộ)?\s*(.+)$/i
  );
  if (numMatch) {
    return {
      houseNumber: numMatch[1].trim(),
      streetQuery: numMatch[2].replace(/^(?:đường|đ\.|phố|đại\s*lộ)\s*/i, '').trim(),
    };
  }

  // Trường hợp không bắt được số nhà ở đầu
  return {
    houseNumber: '',
    streetQuery: firstSegment.replace(/^(?:đường|đ\.|phố|đại\s*lộ)\s*/i, '').trim(),
  };
}

/**
 * Tìm tọa độ GPS chính xác nhất theo tên đường và ngữ cảnh khu vực
 */
export function findStreetCoordinates(
  addressInput?: string | null,
  districtContext?: string | null,
  provinceContext?: string | null
): {
  lat: number;
  lng: number;
  matchedStreet: StreetGeoItem;
  houseNumber: string;
} | null {
  if (!addressInput) return null;

  const { houseNumber, streetQuery } = extractHouseNumberAndStreet(addressInput);
  const targetClean = cleanAddressText(streetQuery || addressInput);
  if (!targetClean || targetClean.length < 2) return null;

  let distClean = districtContext ? cleanAddressText(districtContext) : '';
  const provClean = provinceContext ? cleanAddressText(provinceContext) : '';
  const fullAddressClean = cleanAddressText(addressInput);

  // 1. Lọc các đường khớp tên
  const candidateStreets = VIETNAM_STREETS.filter((s) => {
    if (s.streetNameClean === targetClean) return true;
    if (targetClean.includes(s.streetNameClean)) return true;
    if (s.streetNameClean.includes(targetClean)) return true;
    if (
      s.aliases?.some((a) => {
        const aClean = cleanAddressText(a);
        return aClean === targetClean || targetClean.includes(aClean) || aClean.includes(targetClean);
      })
    ) {
      return true;
    }
    return false;
  });

  if (candidateStreets.length === 0) return null;

  // 1.5. Ưu tiên tuyệt đối phân đoạn khớp với số nhà cụ thể (ví dụ 701 Trần Xuân Soạn -> Phường Tân Hưng)
  if (houseNumber) {
    const hClean = cleanAddressText(houseNumber);
    const matchByHouse = candidateStreets.find((s) => {
      return s.aliases?.some((a) => {
        const aClean = cleanAddressText(a);
        return (
          aClean.includes(`${hClean} `) ||
          aClean.startsWith(`${hClean} `) ||
          aClean.includes(` ${hClean}`) ||
          aClean === `${hClean} ${s.streetNameClean}`
        );
      });
    });
    if (matchByHouse) {
      return {
        lat: matchByHouse.lat,
        lng: matchByHouse.lng,
        matchedStreet: matchByHouse,
        houseNumber,
      };
    }
  }

  // 2. Nếu không truyền districtContext rõ ràng, tự dò từ fullAddressClean
  if (!distClean) {
    for (const s of candidateStreets) {
      if (
        fullAddressClean.includes(s.districtClean) ||
        fullAddressClean.includes(cleanAddressText(s.district))
      ) {
        distClean = s.districtClean;
        break;
      }
    }
  }

  // 3. Nếu có ngữ cảnh quận/huyện, ưu tiên đường nằm đúng quận đó
  //    So theo TỪ nguyên vẹn: "quan 1" không được khớp "quan 12" như kiểu includes trước đây.
  const containsWords = (haystack: string, needle: string) =>
    !!needle && (haystack === needle || (` ${haystack} `).includes(` ${needle} `));
  if (distClean) {
    const matchByDistrict = candidateStreets.find((s) => {
      const sd = cleanAddressText(s.district);
      return (
        containsWords(distClean, s.districtClean) ||
        containsWords(s.districtClean, distClean) ||
        containsWords(sd, distClean)
      );
    });
    if (matchByDistrict) {
      return {
        lat: matchByDistrict.lat,
        lng: matchByDistrict.lng,
        matchedStreet: matchByDistrict,
        houseNumber,
      };
    }
    // Khách (hoặc ô chọn Quận) đã nêu quận mà không có đường cùng tên nào nằm trong quận đó:
    // KHÔNG trả đường ở quận khác. Trước đây "101 Lê Lợi" + Quận Gò Vấp bị trả về tọa độ Lê Lợi Quận 1.
    if (districtContext) return null;
  }

  // 4. Nếu có ngữ cảnh tỉnh/thành phố, ưu tiên đường nằm đúng tỉnh đó
  if (provClean) {
    const matchByProvince = candidateStreets.find((s) =>
      cleanAddressText(s.province).includes(provClean)
    );
    if (matchByProvince) {
      return {
        lat: matchByProvince.lat,
        lng: matchByProvince.lng,
        matchedStreet: matchByProvince,
        houseNumber,
      };
    }
  }

  // 5. Nếu không rõ quận/huyện, chọn ứng viên đầu tiên
  const defaultCandidate = candidateStreets[0];
  return {
    lat: defaultCandidate.lat,
    lng: defaultCandidate.lng,
    matchedStreet: defaultCandidate,
    houseNumber,
  };
}

export interface StreetAutocompleteResult {
  place_id: string;
  description: string;
  main_text: string;
  secondary_text: string;
  source: 'local';
  lat: number;
  lng: number;
  district: string;
  province: string;
  wardHint?: string;
  houseNumber: string;
}

/**
 * Tìm kiếm gợi ý autocomplete từ danh mục đường phố
 */
export function searchStreetSuggestions(
  query: string,
  districtContext?: string | null,
  provinceContext?: string | null,
  wardContextOrLimit?: string | number | null,
  limitArg: number = 10
): StreetAutocompleteResult[] {
  if (!query || query.trim().length < 2) return [];

  let wardContext: string | null | undefined = null;
  let limit = limitArg;
  if (typeof wardContextOrLimit === 'number') {
    limit = wardContextOrLimit;
  } else if (typeof wardContextOrLimit === 'string') {
    wardContext = wardContextOrLimit;
  }

  const { houseNumber, streetQuery } = extractHouseNumberAndStreet(query);
  const targetClean = cleanAddressText(streetQuery || query);
  if (!targetClean || targetClean.length < 2) return [];

  let distClean = districtContext ? cleanAddressText(districtContext) : '';
  const provClean = provinceContext ? cleanAddressText(provinceContext) : '';
  const wardClean = wardContext ? cleanAddressText(wardContext) : '';
  const fullClean = cleanAddressText(query);

  if (!distClean) {
    for (const s of VIETNAM_STREETS) {
      if (
        fullClean.includes(s.districtClean) ||
        fullClean.includes(cleanAddressText(s.district))
      ) {
        distClean = s.districtClean;
        break;
      }
    }
  }

  const scored: Array<{ street: StreetGeoItem; score: number }> = [];

  for (const s of VIETNAM_STREETS) {
    let score = 0;

    if (s.streetNameClean === targetClean) {
      score += 100;
    } else if (s.streetNameClean.startsWith(targetClean)) {
      score += 80;
    } else if (s.streetNameClean.includes(targetClean)) {
      score += 60;
    } else if (targetClean.includes(s.streetNameClean)) {
      score += 50;
    } else if (s.aliases?.some((a) => cleanAddressText(a).includes(targetClean))) {
      score += 45;
    }

    if (score === 0) continue;

    if (distClean && (s.districtClean.includes(distClean) || distClean.includes(s.districtClean))) {
      score += 50;
    }

    if (wardClean && s.wardHint && (cleanAddressText(s.wardHint).includes(wardClean) || wardClean.includes(cleanAddressText(s.wardHint)))) {
      score += 80;
    }

    if (provClean && cleanAddressText(s.province).includes(provClean)) {
      score += 30;
    }

    if (houseNumber) {
      const hClean = cleanAddressText(houseNumber);
      if (
        s.aliases?.some((a) => {
          const aClean = cleanAddressText(a);
          return (
            aClean.includes(`${hClean} `) ||
            aClean.startsWith(`${hClean} `) ||
            aClean.includes(` ${hClean}`) ||
            aClean === `${hClean} ${s.streetNameClean}`
          );
        })
      ) {
        score += 150;
      }
    }

    scored.push({ street: s, score });
  }

  scored.sort((a, b) => b.score - a.score);

  const results: StreetAutocompleteResult[] = [];
  const seenKeys = new Set<string>();

  for (const item of scored) {
    const s = item.street;
    const wardKey = cleanAddressText(s.wardHint || '');
    const key = `${s.streetNameClean}_${s.districtClean}_${wardKey}_${s.province}`;
    if (seenKeys.has(key)) continue;
    seenKeys.add(key);

    const mainText = [houseNumber, s.streetName].filter(Boolean).join(' ');
    const secondaryParts = [s.wardHint, s.district, s.province].filter(Boolean);
    const secondaryText = secondaryParts.join(', ');
    const description = `${mainText}, ${secondaryText}`;

    results.push({
      place_id: `loc_str_${s.districtClean.replace(/\s+/g, '_')}_${wardKey.replace(/\s+/g, '_')}_${s.streetNameClean.replace(/\s+/g, '_')}`,
      description,
      main_text: mainText,
      secondary_text: secondaryText,
      source: 'local',
      lat: s.lat,
      lng: s.lng,
      district: s.district,
      province: s.province,
      wardHint: s.wardHint,
      houseNumber,
    });

    if (results.length >= limit) break;
  }

  return results;
}
